KidsDuaLessonContent _dua({
  required String id,
  required String slug,
  required String categoryId,
  required String title,
  required String arabic,
  required String transliteration,
  required String meaning,
  required String miniLesson,
  required String whenToSay,
  required List<String> chunkArabic,
  required List<String> chunkTransliteration,
  required String sourceType,
  required String sourceReference,
  required String rewardStickerId,
  required int sortOrder,
  required int level,
  required IconData icon,
}) {
  return KidsDuaLessonContent(
    id: id,
    slug: slug,
    categoryId: categoryId,
    title: title,
    arabic: arabic,
    transliteration: transliteration,
    meaning: meaning,
    miniLesson: miniLesson,
    whenToSay: whenToSay,
    phraseChunks: List<KidsDuaPhraseChunk>.generate(
      chunkArabic.length,
      (index) => KidsDuaPhraseChunk(
        id: '$id-${index + 1}',
        arabic: chunkArabic[index],
        transliteration: chunkTransliteration[index],
      ),
      growable: false,
    ),
    sourceType: sourceType,
    sourceReference: sourceReference,
    audioAssetPath: '',
    rewardStickerId: rewardStickerId,
    sortOrder: sortOrder,
    level: level,
    icon: icon,
    practicePrompt: whenToSay,
  );
}

