List<String> importantHadithCollectionOrder() {
  final seen = <String>{};
  final ordered = <String>[];
  for (final item in importantHadithEntries) {
    if (seen.add(item.collectionId)) {
      ordered.add(item.collectionId);
    }
  }
  return ordered;
}

String importantHadithCollectionTitle(String collectionId) {
  for (final item in importantHadithEntries) {
    if (item.collectionId == collectionId) return item.collectionTitle;
  }
  return collectionId;
}

List<ImportantHadithEntry> importantHadithByCollection(String collectionId) {
  return importantHadithEntries
      .where((item) => item.collectionId == collectionId)
      .toList(growable: false);
}

ImportantHadithEntry? importantHadithByNumber(int number) {
  for (final item in importantHadithEntries) {
    if (item.number == number) return item;
  }
  return null;
}
