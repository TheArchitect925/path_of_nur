import '../domain/trivia_models.dart';

TriviaQuestion multipleChoiceQuestion({
  required String id,
  required String categoryId,
  required TriviaDifficulty difficulty,
  required String prompt,
  required List<(String, String)> options,
  required String correctOptionId,
  required String explanation,
  String? quranReference,
  String? sourceReference,
  String? learningNote,
  List<String> tags = const <String>[],
  TriviaContentStatus status = TriviaContentStatus.active,
  bool dailyEligible = true,
  bool featured = false,
  bool beginnerFriendly = false,
  bool reflectionFriendly = false,
  int reviewPrioritySeed = 0,
  List<TriviaMode> modeEligibility = TriviaMode.values,
  String? packId,
  int sortOrder = 0,
  String? cautionFlag,
  String? scholarReviewStatus,
}) {
  return TriviaQuestion(
    id: id,
    categoryId: categoryId,
    type: TriviaQuestionType.multipleChoice,
    difficulty: difficulty,
    prompt: prompt,
    options: options
        .map((item) => TriviaAnswerOption(id: item.$1, label: item.$2))
        .toList(growable: false),
    correctOptionId: correctOptionId,
    explanation: explanation,
    quranReference: quranReference,
    sourceReference: sourceReference,
    learningNote: learningNote,
    tags: tags,
    status: status,
    dailyEligible: dailyEligible,
    featured: featured,
    beginnerFriendly: beginnerFriendly,
    reflectionFriendly: reflectionFriendly,
    reviewPrioritySeed: reviewPrioritySeed,
    modeEligibility: modeEligibility,
    packId: packId,
    sortOrder: sortOrder,
    cautionFlag: cautionFlag,
    scholarReviewStatus: scholarReviewStatus,
  );
}

TriviaQuestion trueFalseQuestion({
  required String id,
  required String categoryId,
  required TriviaDifficulty difficulty,
  required String prompt,
  required bool correct,
  required String explanation,
  String? quranReference,
  String? sourceReference,
  String? learningNote,
  List<String> tags = const <String>[],
  TriviaContentStatus status = TriviaContentStatus.active,
  bool dailyEligible = true,
  bool featured = false,
  bool beginnerFriendly = false,
  bool reflectionFriendly = false,
  int reviewPrioritySeed = 0,
  List<TriviaMode> modeEligibility = TriviaMode.values,
  String? packId,
  int sortOrder = 0,
  String? cautionFlag,
  String? scholarReviewStatus,
}) {
  return TriviaQuestion(
    id: id,
    categoryId: categoryId,
    type: TriviaQuestionType.trueFalse,
    difficulty: difficulty,
    prompt: prompt,
    options: const [
      TriviaAnswerOption(id: 'true', label: 'True'),
      TriviaAnswerOption(id: 'false', label: 'False'),
    ],
    correctOptionId: correct ? 'true' : 'false',
    explanation: explanation,
    quranReference: quranReference,
    sourceReference: sourceReference,
    learningNote: learningNote,
    tags: tags,
    status: status,
    dailyEligible: dailyEligible,
    featured: featured,
    beginnerFriendly: beginnerFriendly,
    reflectionFriendly: reflectionFriendly,
    reviewPrioritySeed: reviewPrioritySeed,
    modeEligibility: modeEligibility,
    packId: packId,
    sortOrder: sortOrder,
    cautionFlag: cautionFlag,
    scholarReviewStatus: scholarReviewStatus,
  );
}
