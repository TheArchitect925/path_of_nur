ArabicLetterDisplayForm _displayFormForResolvedConnections({
  required bool joinsFromPrevious,
  required bool joinsToNext,
}) {
  if (joinsFromPrevious && joinsToNext) {
    return ArabicLetterDisplayForm.medial;
  }
  if (joinsFromPrevious) {
    return ArabicLetterDisplayForm.finalForm;
  }
  if (joinsToNext) {
    return ArabicLetterDisplayForm.initial;
  }
  return ArabicLetterDisplayForm.isolated;
}

List<ArabicResolvedLetterForm> resolveArabicLetterSequenceForms(
  List<String> letterIds,
) {
  final letters = letterIds
      .map(
        (id) =>
            arabicAlphabetLetterById(id) ??
            (throw StateError('Unknown Arabic letter id: $id')),
      )
      .toList(growable: false);

  return List<ArabicResolvedLetterForm>.generate(letters.length, (index) {
    final current = letters[index];
    final previous = index > 0 ? letters[index - 1] : null;
    final next = index + 1 < letters.length ? letters[index + 1] : null;

    final joinsFromPrevious =
        previous != null &&
        previous.joiningBehavior.joinsToNext &&
        current.joiningBehavior.joinsToPrevious;
    final joinsToNext =
        next != null &&
        current.joiningBehavior.joinsToNext &&
        next.joiningBehavior.joinsToPrevious;
    final displayForm = _displayFormForResolvedConnections(
      joinsFromPrevious: joinsFromPrevious,
      joinsToNext: joinsToNext,
    );

    return ArabicResolvedLetterForm(
      letterId: current.id,
      isolatedGlyph: current.glyph,
      displayGlyph: current.positionalForms.glyphForDisplayForm(displayForm),
      displayForm: displayForm,
      joinsFromPrevious: joinsFromPrevious,
      joinsToNext: joinsToNext,
    );
  });
}
