BedtimeStoryQuizOption _option(String id, String text) =>
    BedtimeStoryQuizOption(id: id, text: text);

BedtimeStoryQuizQuestion _question({
  required String id,
  required String prompt,
  required BedtimeStoryQuizQuestionType type,
  required List<BedtimeStoryQuizOption> options,
  required String correctId,
  required String explanation,
}) {
  return BedtimeStoryQuizQuestion(
    questionId: id,
    prompt: prompt,
    questionType: type,
    answerOptions: options,
    correctAnswerId: correctId,
    explanation: explanation,
  );
}

BedtimeStoryMemoryCardPair _pair(String id, String prompt, String answer) =>
    BedtimeStoryMemoryCardPair(pairId: id, prompt: prompt, answer: answer);

