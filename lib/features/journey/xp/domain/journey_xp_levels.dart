LevelDefinition xpLevelForLevel(int level) {
  final safeLevel = level.clamp(1, xpLevelDefinitions.length);
  return xpLevelDefinitions[safeLevel - 1];
}

LevelDefinition xpLevelForTotalXp(int totalXp) {
  for (var index = xpLevelDefinitions.length - 1; index >= 0; index -= 1) {
    final definition = xpLevelDefinitions[index];
    if (totalXp >= definition.totalXpRequired) {
      return definition;
    }
  }
  return xpLevelDefinitions.first;
}

LevelDefinition? xpNextLevelForTotalXp(int totalXp) {
  final current = xpLevelForTotalXp(totalXp);
  final nextIndex = current.level;
  if (nextIndex >= xpLevelDefinitions.length) return null;
  return xpLevelDefinitions[nextIndex];
}
