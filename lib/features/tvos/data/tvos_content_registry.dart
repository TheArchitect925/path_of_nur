  for (final module in tvosContentModuleRegistry) {
    if (module.sectionKey == sectionKey) {
      return module;
    }
  }
  return null;
}

List<TVOSContentModuleDefinition> tvosContentModulesForRoute(String routePath) {
  TVOSRouteContentBundle? bundle;
  for (final item in tvosRouteContentBundles) {
    if (item.routePath == routePath) {
      bundle = item;
      break;
    }
  }
  if (bundle == null) return const <TVOSContentModuleDefinition>[];
  return List<TVOSContentModuleDefinition>.from(bundle.modules)
    ..sort((a, b) => a.order.compareTo(b.order));
}
